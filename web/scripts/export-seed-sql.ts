// Writes supabase/seed.sql from the app's own seed (src/lib/mock), so the database and the
// sample mode never drift apart. Run after changing the seed: npm run db:seed-sql
// Idempotent: re-running the file updates rows in place.
import fs from "fs";
import path from "path";
import { ROLLING_HOUR, SEED_LISTINGS, seedEvents } from "../src/lib/mock/seed";
import { SEED_EVENT_REQUESTS } from "../src/lib/mock/useEventRequests";

type Value = string | number | boolean | null | undefined;

const lit = (v: Value): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "number") {
    if (!Number.isFinite(v)) throw new Error(`not a finite number: ${v}`);
    return String(v);
  }
  return `'${v.replace(/'/g, "''")}'`;
};

function upsert(table: string, rows: Record<string, Value>[]): string {
  if (!rows.length) return "";
  const cols = Object.keys(rows[0]);
  const values = rows.map((r) => `  (${cols.map((c) => lit(r[c])).join(", ")})`).join(",\n");
  const update = cols.filter((c) => c !== "id").map((c) => `${c} = excluded.${c}`).join(", ");
  return `insert into public.${table} (${cols.join(", ")}) values\n${values}\non conflict (id) do update set ${update};\n`;
}

// A fixed clock keeps the file stable between runs. Rolling shows get a placeholder
// starts_at; catalogue_events computes their real date from rolling_hour.
const events = seedEvents(Date.parse("2026-01-01T00:00:00Z"));

const sql = [
  "-- Generated by web/scripts/export-seed-sql.ts from web/src/lib/mock. Do not edit by hand.",
  "-- Catalogue and the admin's event queue. Users, orders and claims come with auth (tahap 4b).",
  "",
  upsert(
    "events",
    events.map((e) => ({
      id: e.id,
      title: e.title,
      category: e.category,
      starts_at: e.dateISO,
      rolling_hour: ROLLING_HOUR[e.id] ?? null,
      venue: e.venue,
      city: e.city,
      image_url: e.image.startsWith("/") ? e.image : null,
      featured: !!e.featured,
      transfer_policy: e.transferPolicy ?? null,
    }))
  ),
  upsert(
    "tiers",
    events.flatMap((e) => e.tiers.map((t, i) => ({ id: t.id, event_id: e.id, name: t.name, face_value: t.faceValue, sort: i })))
  ),
  upsert(
    "listings",
    SEED_LISTINGS.map((l) => ({
      id: l.id,
      event_id: l.eventId,
      tier_id: l.tierId,
      seller_name: l.sellerName,
      ask_price: l.askPrice,
      face_value: l.faceValue,
      quantity: l.quantity,
      splittable: l.splittable,
      gate_ktp: l.gateKtp,
      status: l.status,
      autofilled: l.ai.autofilled,
      forgery_score: l.ai.forgeryScore,
      pdf_suspicious: l.ai.pdfSuspicious,
      barcode_duplicate: l.ai.barcodeDuplicate,
    }))
  ),
  upsert(
    "event_requests",
    SEED_EVENT_REQUESTS.map((r) => ({
      id: r.id,
      submitter_name: r.submittedBy,
      title: r.title,
      starts_at: r.dateISO,
      venue: r.venue,
      city: r.city,
      category: r.category,
      face_values: JSON.stringify(r.faceValues),
      pdf_tier: r.pdfTier,
      organizer_ref: r.organizerRef,
      forgery_score: r.forgeryScore,
      pdf_suspicious: r.pdfSuspicious,
      status: r.status,
    }))
  ),
].join("\n");

const out = path.join(__dirname, "..", "..", "supabase", "seed.sql");
fs.writeFileSync(out, sql);
console.log(`${path.relative(process.cwd(), out)}: ${events.length} events, ${SEED_LISTINGS.length} listings, ${SEED_EVENT_REQUESTS.length} event requests`);
